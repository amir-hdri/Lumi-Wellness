import { expect, test } from "@playwright/test";
import { api, signIn } from "./helpers";

test("management provisions a receptionist from settings with a working password", async ({ page, request }, info) => {
  await signIn(page, request, "admin");
  const email = `staff-${info.project.name}-${Date.now()}@example.test`;
  await page.goto("/admin/settings");
  await page.getByRole("button", { name: "افزودن پذیرش", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("textbox", { name: "نام", exact: true }).fill("پذیرش");
  await dialog.getByRole("textbox", { name: "نام خانوادگی", exact: true }).fill("آزمون");
  await dialog.getByRole("textbox", { name: "ایمیل", exact: true }).fill(email);
  await dialog.getByRole("textbox", { name: "شماره موبایل", exact: true }).fill("09123456789");
  await dialog.getByLabel(/^رمز عبور/).fill("StaffTest123");
  await dialog.getByRole("button", { name: "ثبت کارمند" }).click();
  await expect(dialog).not.toBeVisible();
  const staff = page.getByRole("region", { name: "حساب‌های کارکنان" });
  await expect(staff.getByText(email)).toBeVisible();
  const login = await request.post(`${api}/auth/login`, { data: { email, password: "StaffTest123" } });
  expect(login.ok()).toBeTruthy();
  expect((await login.json()).data.user.role).toBe("receptionist");
  await staff.getByRole("button", { name: "عملیات پذیرش آزمون" }).click();
  await page.getByRole("menuitem", { name: "حذف کارمند" }).click();
  await dialog.getByRole("button", { name: "حذف حساب", exact: true }).click();
  await expect(staff.getByText(email)).toHaveCount(0);
});

test("management creates a login, edits identity, promotes and deletes it", async ({ page, request }, info) => {
  const admin = await signIn(page, request, "admin");
  const email = `panel-${info.project.name}-${Date.now()}@example.test`;
  await page.goto("/admin/members/new");
  await page.getByRole("textbox", { name: "نام", exact: true }).fill("کاربر");
  await page.getByRole("textbox", { name: "نام خانوادگی", exact: true }).fill("آزمون");
  await page.getByRole("textbox", { name: "ایمیل", exact: true }).fill(email);
  await page.getByRole("textbox", { name: "شماره موبایل", exact: true }).fill("09123456789");
  await page.getByLabel(/^رمز عبور/).fill("PanelTest123");
  await page.getByRole("combobox", { name: "شعبه", exact: true }).click();
  await page.getByRole("option").nth(1).click();
  const created = page.waitForResponse((r) => r.url().endsWith("/users") && r.request().method() === "POST");
  await page.getByRole("button", { name: "ثبت عضو", exact: true }).click();
  const response = await created;
  expect(response.ok()).toBeTruthy();
  const id = (await response.json()).data.id;
  await expect(page).toHaveURL(new RegExp(`/admin/members/${id}$`));
  const login = await request.post(`${api}/auth/login`, { data: { email, password: "PanelTest123" } });
  expect(login.ok()).toBeTruthy();
  expect((await request.patch(`${api}/users/${id}/status`, { headers: admin.headers, data: { status: "pending" } })).ok()).toBeTruthy();
  await page.reload();
  await expect(page.locator("main").getByText("در انتظار تأیید", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "عملیات کاربر آزمون" }).click();
  await page.getByRole("menuitem", { name: "ویرایش اطلاعات" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("نام", { exact: true }).fill("ویرایش");
  await dialog.getByRole("combobox", { name: /^شعبه/ }).click();
  await page.getByRole("option", { name: "بدون شعبه" }).click();
  await dialog.getByRole("button", { name: "ذخیره تغییرات" }).click();
  await expect(dialog).not.toBeVisible();
  expect((await (await request.get(`${api}/users/${id}`, { headers: admin.headers })).json()).data.branchId).toBeNull();
  await page.reload();
  await page.getByRole("button", { name: "عملیات ویرایش آزمون" }).click();
  await page.getByRole("menuitem", { name: "تغییر نقش", exact: true }).click();
  await dialog.getByLabel("نقش حساب").selectOption("receptionist");
  await dialog.getByRole("button", { name: "ثبت نقش جدید" }).click();
  await expect(dialog).not.toBeVisible();
  await page.goto("/admin/settings");
  const staff = page.getByRole("region", { name: "حساب‌های کارکنان" });
  await expect(staff.getByText(email)).toBeVisible();
  await staff.getByRole("button", { name: "عملیات ویرایش آزمون" }).click();
  await page.getByRole("menuitem", { name: "حذف کارمند" }).click();
  await dialog.getByRole("button", { name: "حذف حساب", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(staff.getByText(email)).toHaveCount(0);
  expect((await request.get(`${api}/users/${id}`, { headers: admin.headers })).status()).toBe(404);
});

test("management assigns, freezes and resumes membership then reconciles a payment", async ({ page, request }, info) => {
  const admin = await signIn(page, request, "admin");
  const name = `عضویت ${info.project.name} ${Date.now()}`;
  const result = await request.post(`${api}/users`, { headers: admin.headers, data: {
    email: `membership-${Date.now()}@example.test`, password: "PanelTest123", firstName: name, lastName: "آزمون", phone: "09123456789",
  } });
  expect(result.ok()).toBeTruthy();
  const member = (await result.json()).data;
  await page.goto(`/admin/members/${member.id}`);
  await page.getByRole("button", { name: "تخصیص پلن اشتراک" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("combobox", { name: /^پلن اشتراک/ }).click();
  await page.getByRole("option").first().click();
  await dialog.getByRole("combobox", { name: /^شعبه/ }).click();
  await page.getByRole("option").first().click();
  await dialog.getByRole("button", { name: "تخصیص پلن", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "توقف اشتراک", exact: true }).click();
  await dialog.getByLabel("دلیل توقف").fill("استراحت آزمایشی");
  await dialog.getByRole("button", { name: "توقف اشتراک", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "فعال‌سازی دوباره اشتراک" }).click();
  await expect(page.getByRole("button", { name: "توقف اشتراک", exact: true })).toBeVisible();
  await page.goto("/admin/payments");
  await page.getByRole("button", { name: "ثبت پرداخت", exact: true }).click();
  await dialog.getByRole("combobox", { name: /^عضو/ }).click();
  await page.getByRole("option", { name: `${name} آزمون`, exact: true }).click();
  await dialog.getByLabel("مبلغ (ریال)").fill("125000");
  const saved = page.waitForResponse((r) => r.url().endsWith("/payments") && r.request().method() === "POST");
  await dialog.getByRole("button", { name: "ثبت پرداخت", exact: true }).click();
  const response = await saved;
  expect(response.ok()).toBeTruthy();
  const payment = (await response.json()).data;
  expect(payment.status).toBe("pending");
  await page.goto(`/admin/payments/${payment.id}`);
  await page.getByRole("button", { name: /عملیات تراکنش/ }).click();
  await page.getByRole("menuitem", { name: "موفق", exact: true }).click();
  await expect(page.locator("main").getByText("موفق", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator("main").getByText("موفق", { exact: true })).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "دریافت رسید متنی" }).click();
  expect((await download).suggestedFilename()).toBe(`lumi-receipt-${payment.id}.txt`);
  expect((await request.get(`${api}/payments/${payment.id}`, { headers: admin.headers })).ok()).toBeTruthy();
});
